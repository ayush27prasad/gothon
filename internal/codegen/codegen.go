// Package codegen turns the task signatures exported by a Python module into a
// typed Go client package.
package codegen

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/ayush27prasad/gothon/internal/schema"
)

// Options controls the generated package.
type Options struct {
	Module  string // Python module, e.g. "ner"
	Package string // Go package name; defaults to the last part of Module
	Version string // gothon version, recorded in the header
}

// Generate returns the formatted Go source of the client package for e.
func Generate(e *schema.Export, opts Options) ([]byte, error) {
	if opts.Package == "" {
		opts.Package = opts.Module[strings.LastIndex(opts.Module, ".")+1:]
	}
	g := &gen{defs: e.Defs, names: map[string]string{}, input: map[string]bool{}}
	for name := range e.Defs {
		g.names[name] = g.typeName(name)
	}
	for _, t := range e.Tasks {
		g.markInput(t.Input)
	}
	// Settings share the namespace of the model types.
	taken := map[string]bool{}
	for _, n := range g.names {
		taken[n] = true
	}
	settingsNames := make([]string, len(e.Settings))
	for i, st := range e.Settings {
		settingsNames[i] = unique(g.typeName(st.Name), taken)
		for _, f := range st.Fields {
			g.markInput(f.Schema) // Go fills these in, like task inputs
		}
	}

	var methods []method
	used := map[string]bool{"Close": true, "Pool": true}
	for _, t := range e.Tasks {
		m := method{task: t.Name, doc: t.Doc, name: unique(goName(t.Name), used)}
		var err error
		if t.Input != nil {
			if m.in, err = g.goType(t.Input, t.Name+" input"); err != nil {
				return nil, err
			}
		}
		if t.Output != nil && t.Output.Type != "null" {
			if m.out, err = g.goType(t.Output, t.Name+" output"); err != nil {
				return nil, err
			}
		}
		methods = append(methods, m)
	}

	var types strings.Builder
	for i, st := range e.Settings {
		if err := g.writeSettings(&types, settingsNames[i], st); err != nil {
			return nil, err
		}
	}
	names := make([]string, 0, len(e.Defs))
	for name := range e.Defs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := g.writeType(&types, name, e.Defs[name]); err != nil {
			return nil, err
		}
	}

	var b strings.Builder
	version := opts.Version
	if version == "" {
		version = "(devel)"
	}
	fmt.Fprintf(&b, "// Code generated by gothon gen %s. DO NOT EDIT.\n\n", version)
	fmt.Fprintf(&b, "// Package %s calls the tasks of the Python module %q.\n", opts.Package, opts.Module)
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	single := len(e.Settings) == 1
	b.WriteString("import (\n\t\"context\"\n")
	if single {
		b.WriteString("\t\"slices\"\n")
	}
	if g.usesTime {
		b.WriteString("\t\"time\"\n")
	}
	b.WriteString("\n\t\"github.com/ayush27prasad/gothon\"\n)\n\n")
	b.WriteString("const _ = gothon.SupportPackageIsVersion1\n\n")
	b.WriteString("const (\n")
	b.WriteString("\t// Module is the Python module these tasks live in.\n")
	fmt.Fprintf(&b, "\tModule = %q\n", opts.Module)
	b.WriteString("\t// SchemaHash identifies the task signatures this code was generated from.\n")
	fmt.Fprintf(&b, "\tSchemaHash = %q\n)\n\n", e.Hash)

	fmt.Fprintf(&b, "// Tasks is the set of tasks in %q. Client implements it; fakes can too.\n", opts.Module)
	b.WriteString("type Tasks interface {\n")
	for _, m := range methods {
		fmt.Fprintf(&b, "\t%s\n", m.signature())
	}
	b.WriteString("}\n\n")

	b.WriteString("// Config configures the client. Module sets up the worker processes and the\n")
	b.WriteString("// defaults for every task; Tasks overrides individual tasks. The most specific\n")
	b.WriteString("// non-zero setting wins, falling back to the Runtime's defaults.\n")
	b.WriteString("type Config struct {\n\tModule gothon.ModuleConfig\n\tTasks  TaskConfigs\n}\n\n")
	fmt.Fprintf(&b, "// TaskConfigs holds one configuration per task in %q.\n", opts.Module)
	b.WriteString("type TaskConfigs struct {\n")
	for _, m := range methods {
		fmt.Fprintf(&b, "\t%s gothon.TaskConfig\n", m.name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// Client runs the tasks on a pool of Python workers.\n")
	b.WriteString("type Client struct {\n\tpool *gothon.Pool\n}\n\n")
	b.WriteString("var _ Tasks = (*Client)(nil)\n\n")
	if single {
		fmt.Fprintf(&b, "// Start launches workers for %q on rt, configured by settings.\n", opts.Module)
		fmt.Fprintf(&b, "func Start(ctx context.Context, rt *gothon.Runtime, cfg Config, settings %s) (*Client, error) {\n", settingsNames[0])
	} else {
		fmt.Fprintf(&b, "// Start launches workers for %q on rt.\n", opts.Module)
		if len(e.Settings) > 1 {
			b.WriteString("// Add each settings type to cfg.Module.Env with its Env method.\n")
		}
		b.WriteString("func Start(ctx context.Context, rt *gothon.Runtime, cfg Config) (*Client, error) {\n")
	}
	b.WriteString("\tm := cfg.Module\n\tm.Name = Module\n\tm.SchemaHash = SchemaHash\n")
	b.WriteString("\tm.Tasks = map[string]gothon.TaskConfig{\n")
	for _, m := range methods {
		fmt.Fprintf(&b, "\t\t%q: cfg.Tasks.%s,\n", m.task, m.name)
	}
	b.WriteString("\t}\n")
	if single {
		b.WriteString("\tm.Env = append(slices.Clip(m.Env), settings.Env()...)\n")
	}
	b.WriteString("\tp, err := rt.Start(ctx, m)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\treturn &Client{pool: p}, nil\n}\n\n")
	b.WriteString("// Pool returns the underlying worker pool.\n")
	b.WriteString("func (c *Client) Pool() *gothon.Pool { return c.pool }\n\n")
	b.WriteString("// Close stops the workers.\n")
	b.WriteString("func (c *Client) Close() error { return c.pool.Close() }\n")
	for _, m := range methods {
		b.WriteString("\n")
		m.write(&b)
	}
	b.WriteString(types.String())

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("codegen: format: %w\n%s", err, b.String())
	}
	return src, nil
}

type method struct {
	task, doc, name string
	in, out         string // Go types; empty when the task takes no input or returns None
}

func (m method) signature() string {
	params := "ctx context.Context"
	if m.in != "" {
		params += ", in " + m.in
	}
	if m.out == "" {
		return fmt.Sprintf("%s(%s) error", m.name, params)
	}
	return fmt.Sprintf("%s(%s) (%s, error)", m.name, params, m.out)
}

func (m method) write(b *strings.Builder) {
	fmt.Fprintf(b, "// %s runs the Python task %q.\n", m.name, m.task)
	if m.doc != "" {
		b.WriteString("//\n")
		writeComment(b, "", m.doc)
	}
	fmt.Fprintf(b, "func (c *Client) %s {\n", m.signature())
	in := "nil"
	if m.in != "" {
		in = "in"
	}
	if m.out == "" {
		fmt.Fprintf(b, "\treturn c.pool.Call(ctx, %q, %s, nil)\n}\n", m.task, in)
		return
	}
	fmt.Fprintf(b, "\tvar out %s\n", m.out)
	fmt.Fprintf(b, "\terr := c.pool.Call(ctx, %q, %s, &out)\n", m.task, in)
	b.WriteString("\treturn out, err\n}\n")
}

type gen struct {
	defs     map[string]*schema.Schema
	names    map[string]string // def name → Go type name
	input    map[string]bool   // defs reachable from a task input
	usesTime bool
}

// markInput records every def reachable from s. Optional fields of those types
// become pointers, so a value left unset in Go keeps its Python default.
func (g *gen) markInput(s *schema.Schema) {
	if s == nil {
		return
	}
	if name := refName(s.Ref); name != "" {
		if g.input[name] {
			return
		}
		g.input[name] = true
		s = g.defs[name]
		if s == nil {
			return
		}
	}
	for _, p := range s.Properties {
		g.markInput(p.Schema)
	}
	for _, list := range [][]*schema.Schema{s.AnyOf, s.AllOf, s.OneOf, s.PrefixItems} {
		for _, x := range list {
			g.markInput(x)
		}
	}
	g.markInput(s.Items)
	g.markInput(s.AdditionalProperties)
}

// goType maps a schema to a Go type. where names the location for error messages.
func (g *gen) goType(s *schema.Schema, where string) (string, error) {
	if name := refName(s.Ref); name != "" {
		goName, ok := g.names[name]
		if !ok {
			return "", fmt.Errorf("%s: unknown type %q", where, name)
		}
		return goName, nil
	}
	if len(s.AllOf) == 1 {
		return g.goType(s.AllOf[0], where)
	}
	if len(s.AnyOf) > 0 {
		inner := nonNull(s.AnyOf)
		if inner == nil {
			return "", fmt.Errorf("%s: unions are not supported; use a single type, optionally with None", where)
		}
		t, err := g.goType(inner, where)
		if err != nil {
			return "", err
		}
		return pointer(t), nil
	}
	if len(s.OneOf) > 0 {
		return "", fmt.Errorf("%s: unions are not supported; use a single type, optionally with None", where)
	}
	if len(s.PrefixItems) > 0 {
		return "", fmt.Errorf("%s: tuples are not supported; use a list or a model", where)
	}
	switch s.Type {
	case "string":
		if s.Format == "date-time" {
			g.usesTime = true
			return "time.Time", nil
		}
		return "string", nil
	case "integer":
		return "int", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		if s.Items == nil {
			return "[]any", nil
		}
		t, err := g.goType(s.Items, where+"[]")
		return "[]" + t, err
	case "object":
		if len(s.Properties) > 0 {
			return "", fmt.Errorf("%s: inline objects are not supported; use a pydantic model", where)
		}
		if s.AdditionalProperties == nil {
			return "map[string]any", nil
		}
		t, err := g.goType(s.AdditionalProperties, where+"{}")
		return "map[string]" + t, err
	case "":
		if s.Const == nil && len(s.Enum) == 0 {
			return "any", nil // typing.Any or no annotation
		}
	}
	return "", fmt.Errorf("%s: unsupported schema (type %q)", where, s.Type)
}

func (g *gen) writeType(b *strings.Builder, defName string, s *schema.Schema) error {
	name := g.names[defName]
	b.WriteString("\n")
	fmt.Fprintf(b, "// %s mirrors the Python type %s.\n", name, defName)
	if s.Description != "" {
		b.WriteString("//\n")
		writeComment(b, "", s.Description)
	}

	if len(s.Enum) > 0 {
		base := map[string]string{"string": "string", "integer": "int"}[s.Type]
		if base == "" {
			return fmt.Errorf("%s: enums must be all strings or all integers", defName)
		}
		fmt.Fprintf(b, "type %s %s\n\n", name, base)
		b.WriteString("const (\n")
		used := map[string]bool{}
		for _, v := range s.Enum {
			lit := fmt.Sprint(v)
			if base == "string" {
				lit = strconv.Quote(fmt.Sprint(v))
			}
			fmt.Fprintf(b, "\t%s %s = %s\n", unique(name+goName(fmt.Sprint(v)), used), name, lit)
		}
		b.WriteString(")\n")
		return nil
	}
	if s.Type != "object" {
		return fmt.Errorf("%s: unsupported named type (type %q)", defName, s.Type)
	}

	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	fmt.Fprintf(b, "type %s struct {\n", name)
	used := map[string]bool{}
	for _, p := range s.Properties {
		where := defName + "." + p.Name
		// Fields of output-only types are always present in what Python sends back.
		optional := g.input[defName] && !required[p.Name]
		t, err := g.goType(p.Schema, where)
		if err != nil {
			return err
		}
		if optional && !strings.HasPrefix(t, "*") && !strings.HasPrefix(t, "[]") &&
			!strings.HasPrefix(t, "map[") && t != "any" {
			t = "*" + t
		}
		tag := p.Name
		if optional {
			tag += ",omitempty"
		}
		if p.Schema.Description != "" {
			writeComment(b, "\t", p.Schema.Description)
		}
		if enum := p.Schema.Enum; len(enum) > 0 {
			fmt.Fprintf(b, "\t// One of: %s.\n", quoteAll(enum))
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", unique(goName(p.Name), used), t, tag)
	}
	b.WriteString("}\n")
	return nil
}

func (g *gen) writeSettings(b *strings.Builder, name string, st schema.Settings) error {
	fmt.Fprintf(b, "\n// %s mirrors the Python settings class %s. Each field is passed to the\n", name, st.Name)
	b.WriteString("// workers as the environment variable named in its comment.\n")
	if st.Doc != "" {
		b.WriteString("//\n")
		writeComment(b, "", st.Doc)
	}
	fmt.Fprintf(b, "type %s struct {\n", name)
	used := map[string]bool{}
	fields := make([]string, len(st.Fields))
	for i, f := range st.Fields {
		t, err := g.goType(f.Schema, st.Name+"."+f.Name)
		if err != nil {
			return err
		}
		if !f.Required {
			t = pointer(t)
		}
		fields[i] = unique(goName(f.Name), used)
		note := "required"
		if !f.Required {
			note = "optional; nil keeps the Python default"
		}
		fmt.Fprintf(b, "\t// %s is read from %s (%s).\n", fields[i], f.Env, note)
		if f.Schema.Description != "" {
			writeComment(b, "\t", f.Schema.Description)
		}
		fmt.Fprintf(b, "\t%s %s\n", fields[i], t)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// Env returns the environment variables that configure %s in the workers.\n", st.Name)
	b.WriteString("// Zero values of required fields are left out, so Python reports them as missing.\n")
	fmt.Fprintf(b, "func (s %s) Env() []string {\n\treturn gothon.SettingsEnv(\n", name)
	for i, f := range st.Fields {
		fmt.Fprintf(b, "\t\t%q, s.%s,\n", f.Env, fields[i])
	}
	b.WriteString("\t)\n}\n")
	return nil
}

// typeName picks a Go name for a def that cannot clash with the generated API.
func (g *gen) typeName(def string) string {
	n := goName(def)
	switch n {
	case "Tasks", "Client", "Start", "Module", "SchemaHash":
		n += "Type"
	}
	return n
}

func refName(ref string) string {
	return strings.TrimPrefix(ref, "#/$defs/")
}

func nonNull(anyOf []*schema.Schema) *schema.Schema {
	if len(anyOf) != 2 {
		return nil
	}
	switch {
	case anyOf[1].Type == "null" && anyOf[0].Type != "null":
		return anyOf[0]
	case anyOf[0].Type == "null" && anyOf[1].Type != "null":
		return anyOf[1]
	}
	return nil
}

// pointer makes t nullable. Slices, maps and any already are.
func pointer(t string) string {
	if strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "map[") || strings.HasPrefix(t, "*") || t == "any" {
		return t
	}
	return "*" + t
}

var initialisms = map[string]bool{
	"api": true, "cpu": true, "css": true, "db": true, "dns": true, "gpu": true, "html": true,
	"http": true, "https": true, "id": true, "ids": true, "io": true, "ip": true, "json": true,
	"llm": true, "ml": true, "os": true, "pdf": true, "sql": true, "ssh": true, "tcp": true,
	"tls": true, "ttl": true, "ui": true, "uid": true, "uri": true, "url": true, "urls": true,
	"utc": true, "uuid": true, "xml": true,
}

// goName converts snake_case, camelCase or arbitrary text to an exported Go identifier.
func goName(s string) string {
	var words []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			words = append(words, string(cur))
			cur = nil
		}
	}
	rs := []rune(s)
	for i, r := range rs {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
		case unicode.IsUpper(r) && len(cur) > 0 &&
			(unicode.IsLower(cur[len(cur)-1]) || (i+1 < len(rs) && unicode.IsLower(rs[i+1]))):
			flush()
			cur = append(cur, r)
		default:
			cur = append(cur, r)
		}
	}
	flush()

	var b strings.Builder
	for _, w := range words {
		lw := strings.ToLower(w)
		switch {
		case initialisms[lw]:
			if lw == "ids" || lw == "urls" {
				b.WriteString(strings.ToUpper(lw[:len(lw)-1]) + "s")
			} else {
				b.WriteString(strings.ToUpper(lw))
			}
		default:
			r := []rune(w)
			b.WriteString(string(unicode.ToUpper(r[0])) + string(r[1:]))
		}
	}
	n := b.String()
	if n == "" || unicode.IsDigit([]rune(n)[0]) {
		n = "X" + n
	}
	return n
}

func unique(n string, used map[string]bool) string {
	out := n
	for i := 2; used[out]; i++ {
		out = n + strconv.Itoa(i)
	}
	used[out] = true
	return out
}

func writeComment(b *strings.Builder, indent, text string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
		} else {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}

func quoteAll(vs []any) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		if s, ok := v.(string); ok {
			q[i] = strconv.Quote(s)
		} else {
			q[i] = fmt.Sprint(v)
		}
	}
	return strings.Join(q, ", ")
}
